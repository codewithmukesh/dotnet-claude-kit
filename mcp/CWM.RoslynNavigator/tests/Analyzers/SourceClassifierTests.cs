using CWM.RoslynNavigator.Analyzers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace CWM.RoslynNavigator.Tests.Analyzers;

public class SourceClassifierTests
{
    private static SourceKind Classify(string relativePath, bool isTestProject = false, string source = "class C { }")
    {
        var tree = CSharpSyntaxTree.ParseText(source, path: relativePath);
        return SourceClassifier.Classify(tree, relativePath, isTestProject, TestContext.Current.CancellationToken);
    }

    [Theory]
    [InlineData("src/Api/obj/Debug/net10.0/Api.GlobalUsings.g.cs")]
    [InlineData("src/Api/bin/Release/net10.0/Thing.cs")]
    [InlineData("src/Api/Models.Designer.cs")]
    [InlineData("src/Api/Contracts.generated.cs")]
    [InlineData("src/Api/obj/Api.AssemblyInfo.cs")]
    public void Classify_GeneratedPath_IsGenerated(string path) =>
        Assert.Equal(SourceKind.Generated, Classify(path));

    [Fact]
    public void Classify_AutoGeneratedHeader_IsGenerated()
    {
        var source = "// <auto-generated/>\nclass C { }";
        Assert.Equal(SourceKind.Generated, Classify("src/Api/Handwritten.cs", source: source));
    }

    [Theory]
    [InlineData("src/Api/Migrations/20240101_Init.cs")]
    [InlineData("src/Api/Data/AppDbContextModelSnapshot.cs")]
    public void Classify_MigrationPath_IsMigration(string path) =>
        Assert.Equal(SourceKind.Migration, Classify(path));

    [Theory]
    [InlineData("tests/Api.Tests/OrderTests.cs")]
    [InlineData("src/Api/OrderServiceTests.cs")]
    [InlineData("src/Api/OrderSpec.cs")]
    [InlineData("src/Api/IntegrationTestBase.cs")]
    public void Classify_TestPath_IsTest(string path) =>
        Assert.Equal(SourceKind.Test, Classify(path));

    [Fact]
    public void Classify_AnyFileInTestProject_IsTest() =>
        Assert.Equal(SourceKind.Test, Classify("src/Api/Helpers.cs", isTestProject: true));

    [Theory]
    [InlineData("src/Api/OrderService.cs")]
    [InlineData("src/Api/Features/Orders/CreateOrder.cs")]
    public void Classify_OrdinaryPath_IsProduction(string path) =>
        Assert.Equal(SourceKind.Production, Classify(path));

    [Theory]
    [InlineData("src/Api/Contest.cs")]
    [InlineData("src/Api/Manifest.cs")]
    [InlineData("src/Api/LatestOrder.cs")]
    public void Classify_ProductionNameEndingInTest_IsProduction(string path) =>
        Assert.Equal(SourceKind.Production, Classify(path));

    [Fact]
    public void Classify_ObjectsFolder_IsProduction() =>
        Assert.Equal(SourceKind.Production, Classify("src/Api/Objects/Order.cs"));

    [Fact]
    public void Classify_GeneratedFileInTestProject_IsGenerated() =>
        Assert.Equal(
            SourceKind.Generated,
            Classify("tests/Api.Tests/obj/Debug/Api.g.cs", isTestProject: true));

    private static Project CreateProject(string name, params Type[] referencedTypes)
    {
        using var workspace = new AdhocWorkspace();
        return workspace.AddProject(ProjectInfo.Create(
            ProjectId.CreateNewId(),
            VersionStamp.Default,
            name,
            name,
            LanguageNames.CSharp,
            metadataReferences: referencedTypes
                .Select(t => MetadataReference.CreateFromFile(t.Assembly.Location))));
    }

    [Fact]
    public void IsTestProject_TestFrameworkMetadataReference_IsTestProject() =>
        // xunit.v3.core.dll, referenced the way a package reference reaches the project.
        Assert.True(SourceClassifier.IsTestProject(CreateProject("Widgets.Verification", typeof(object), typeof(FactAttribute))));

    [Fact]
    public void IsTestProject_NoTestFrameworkReference_IsNotTestProject() =>
        Assert.False(SourceClassifier.IsTestProject(CreateProject("Widgets.Core", typeof(object))));

    [Theory]
    [InlineData("Widgets.Tests")]
    [InlineData("Widgets.UnitTest")]
    [InlineData("Widgets.Tests.Integration")]
    public void IsTestProject_TestProjectName_IsTestProjectWithoutReferences(string name) =>
        Assert.True(SourceClassifier.IsTestProject(CreateProject(name)));
}
